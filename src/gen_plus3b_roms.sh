#!/bin/sh
# One-time generator: builds src/plus3b_roms.h from ../roms/plus3b/plus3b_{0,1,2,3}.rom
# Run from the directory where this script lives (src/).
# Output is checked afterwards: each array must hold exactly 16384 (0x4000) bytes.
set -e

ROMS_DIR="../roms/plus3b"
OUT="plus3b_roms.h"

for i in 0 1 2 3; do
  if [ ! -f "${ROMS_DIR}/plus3b_${i}.rom" ]; then
    echo "ERROR: missing ${ROMS_DIR}/plus3b_${i}.rom" >&2
    exit 1
  fi
  SIZE=$(wc -c < "${ROMS_DIR}/plus3b_${i}.rom")
  if [ "$SIZE" -ne 16384 ]; then
    echo "ERROR: plus3b_${i}.rom is $SIZE bytes, expected 16384" >&2
    exit 1
  fi
done

{
  cat <<'HDR'
/*
 * ZX Spectrum +3 ROM pages 0-3
 * Copyright (c) Amstrad plc
 *
 * These ROMs are redistributed with permission from Amstrad.
 * They are not covered by the MIT License used for the rest of this project.
 *
 * These files must not be assumed to be freely reusable under MIT terms.
 *
 * Generated by gen_plus3b_roms.sh from ../roms/plus3b/plus3b_{0,1,2,3}.rom
 * Do not edit manually.
 */
#ifndef PLUS3B_ROMS_H
#define PLUS3B_ROMS_H

#include <stdint.h>

#ifdef __cplusplus
extern "C" {
#endif
HDR

  i=0
  while [ $i -le 3 ]; do
    echo
    echo "/* Source: ${ROMS_DIR}/plus3b_${i}.rom (16384 bytes) */"
    echo "const uint8_t plus3b_${i}_rom[0x4000] __attribute__((aligned(4))) = {"
    od -An -tu1 -v "${ROMS_DIR}/plus3b_${i}.rom" | awk '
      {
        for (j = 1; j <= NF; j++) {
          printf "0x%02x,", $j
          k++
          if (k == 16) { printf "\n"; k = 0 }
        }
      }
    '
    echo "};"
    i=$((i + 1))
  done

  cat <<'FTR'

#ifdef __cplusplus
} /* extern "C" */
#endif

#endif /* PLUS3B_ROMS_H */
FTR
} > "$OUT"

echo "Generated $OUT"
