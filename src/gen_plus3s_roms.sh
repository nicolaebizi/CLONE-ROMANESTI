#!/bin/sh
# One-time generator: builds src/plus3s_rom.h from the verified +3s ROM dumps
# (Cristian Secară's machine, NEWEPR0-3_clean.rom, 4 x 16384 bytes).
# Run from the directory where this script lives (src/).
# Output is checked afterwards: each array must hold exactly 16384 (0x4000) bytes.
set -e

ROMS_DIR="${PLUS3S_ROMS_DIR:-/Users/nicolaemuntean/Documents/proiecte_soft/PLUS3S/+3s_ROMs/clean}"
OUT="plus3s_rom.h"

for i in 0 1 2 3; do
  if [ ! -f "${ROMS_DIR}/NEWEPR${i}_clean.rom" ]; then
    echo "ERROR: missing ${ROMS_DIR}/NEWEPR${i}_clean.rom" >&2
    exit 1
  fi
  SIZE=$(wc -c < "${ROMS_DIR}/NEWEPR${i}_clean.rom")
  if [ "$SIZE" -ne 16384 ]; then
    echo "ERROR: NEWEPR${i}_clean.rom is $SIZE bytes, expected 16384" >&2
    exit 1
  fi
done

{
  cat <<'HDR'
/*
 * ZX Spectrum +3s ROM pages 0-3 (Cristian Secară's modified machine ROMs).
 * Source dumps: NEWEPR0_clean.rom .. NEWEPR3_clean.rom (user-verified).
 *
 * Copyright of the underlying +3 ROMs: Amstrad plc; the +3s modifications
 * are (c) Cristian Secară. Not covered by the MIT License used for the rest
 * of this project; must not be assumed to be freely reusable.
 *
 * Generated by gen_plus3s_roms.sh. Do not edit manually.
 */
#ifndef PLUS3S_ROMS_H
#define PLUS3S_ROMS_H

#include <stdint.h>

#ifdef __cplusplus
extern "C" {
#endif
HDR

  i=0
  while [ $i -le 3 ]; do
    echo
    echo "/* Source: NEWEPR${i}_clean.rom (16384 bytes) */"
    echo "const uint8_t plus3s_${i}_rom[0x4000] __attribute__((aligned(4))) = {"
    od -An -tu1 -v "${ROMS_DIR}/NEWEPR${i}_clean.rom" | awk '
      {
        for (j = 1; j <= NF; j++) {
          printf "0x%02x,", $j
          k++
          if (k == 16) { printf "\n"; k = 0 }
        }
      }
    '
    echo "};"
    i=$((i + 1))
  done

  cat <<'FTR'

#ifdef __cplusplus
} /* extern "C" */
#endif

#endif /* PLUS3S_ROMS_H */
FTR
} > "$OUT"

echo "Generated $OUT"
